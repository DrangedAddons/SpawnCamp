"""Builds RareData.lua from the vmangos world database (SQLite release).

    python tools/build_rares.py path/to/mangos.sqlite [path/to/SilverDragon]

Get mangos.sqlite from the db-sqlite-*.zip asset of the vmangos/core
"db_latest" release (https://github.com/vmangos/core/releases/tag/db_latest).

Takes every rare (rank 4) and rare elite (rank 2) creature with an open-world
spawn in patch 1.12 (Eastern Kingdoms = 0, Kalimdor = 1). Points are world
coordinates; the addon turns them into zone/map coordinates in game with
C_Map, so no zone table has to be shipped. Patrolling rares also get a few
points along their path, spaced out.
"""
import math
import re
import os
import sqlite3
import sys

PATCH = 10          # vmangos patch index for 1.12
PATH_SPACING = 60   # yards between kept patrol points
PATH_MAX = 8
SKIP_WORDS = ("[PH]", "UNUSED", "(test)", "[DNT]", "TEST ")


def main(db_path):
    c = sqlite3.connect(db_path)
    rares = c.execute(
        """select t.entry, t.name, t.level_min, t.level_max, t.rank
           from creature_template t
           where t.rank in (2, 4) and t.patch = (
               select max(x.patch) from creature_template x
               where x.entry = t.entry and x.patch <= ?)
           order by t.entry""", (PATCH,)).fetchall()
    out = []
    for entry, name, lmin, lmax, rank in rares:
        if any(w.lower() in name.lower() for w in SKIP_WORDS):
            continue
        spawns = c.execute(
            """select guid, map, position_x, position_y, spawntimesecsmin, spawntimesecsmax
               from creature
               where ? in (id, id2, id3, id4, id5) and map in (0, 1)
                 and patch_min <= ? and patch_max >= ?
               order by guid""", (entry, PATCH, PATCH)).fetchall()
        if not spawns:
            continue
        cont = spawns[0][1]
        spawns = [s for s in spawns if s[1] == cont]
        rmin = min(s[4] for s in spawns)
        rmax = max(s[5] for s in spawns)
        pts = [(round(s[2]), round(s[3])) for s in spawns]
        nspawn = len(pts)
        path = c.execute(
            "select position_x, position_y from creature_movement_template where entry = ? order by path_id, point",
            (entry,)).fetchall()
        for s in spawns:
            path += c.execute(
                "select position_x, position_y from creature_movement where id = ? order by point",
                (s[0],)).fetchall()
        kept = []
        for x, y in path:
            if len(kept) >= PATH_MAX:
                break
            if all(math.hypot(x - a, y - b) >= PATH_SPACING for a, b in pts + kept):
                kept.append((round(x), round(y)))
        pts += kept
        flat = ",".join(f"{x},{y}" for x, y in pts)
        lua_name = name.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'[{entry}]={{"{lua_name}",{lmin},{lmax},{1 if rank == 2 else 0},{cont},{rmin},{rmax},{nspawn},{{{flat}}}}},')
    forever = read_silverdragon_forever(sd_path) if sd_path else []
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(here, "RareData.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Rare spawns, generated by tools/build_rares.py. Do not edit by hand.\n")
        f.write("local _, SC = ...\n\n")
        f.write("-- Vanilla 1.12 reference, from the vmangos world database (github.com/vmangos/core).\n")
        f.write("-- [npcId] = { name, minLevel, maxLevel, elite, continent, respawnMin, respawnMax,\n")
        f.write("--             spawnCount, { worldX, worldY, ... } }  (spawn points first, then patrol points)\n")
        f.write("SC.RARE_DATA = {\n")
        f.write("\n".join(out))
        f.write("\n}\n\n")
        f.write("-- Forever-only rares, from SilverDragon's Data/Forever zone files (by Kemayo,\n")
        f.write("-- used with permission). [npcId] = { name, uiMapID, { x, y, ... } } in 0-1 map coords.\n")
        f.write("SC.RARE_FOREVER = {\n")
        for npc, name, zone, pts in forever:
            flat = ",".join(f"{x:.3f},{y:.3f}" for x, y in pts)
            lua_name = name.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'[{npc}]={{"{lua_name}",{zone},{{{flat}}}}},\n')
        f.write("}\n")
    print(f"{len(out)} vanilla rares, {len(forever)} Forever rares written")


def read_silverdragon_forever(sd_path):
    """Reads SilverDragon/Data/Forever: constants.lua names the zone ids, each
    zones/*.lua is a RegisterPoints(zone, { [xxxxyyyy] = { label=, npc= } })."""
    base = os.path.join(sd_path, "Data", "Forever")
    consts = dict(re.findall(r"ns\.(\w+)\s*=\s*(\d+)", open(os.path.join(base, "constants.lua"), encoding="utf-8").read()))
    out = {}
    zdir = os.path.join(base, "zones")
    for fn in sorted(os.listdir(zdir)):
        src = open(os.path.join(zdir, fn), encoding="utf-8").read()
        m = re.search(r"RegisterPoints\(ns\.(\w+)", src)
        if not m or m.group(1) not in consts:
            continue
        zone = int(consts[m.group(1)])
        # One chunk per point: "[60203460] = { ... }".
        for coord, body in re.findall(r"\[(\d{8})\]\s*=\s*\{(.*?)\n\t\},", src, re.S):
            npc = re.search(r"\bnpc\s*=\s*(\d+)", body)
            label = re.search(r'label\s*=\s*"([^"]*)"', body)
            name = None
            if label:
                tag = re.match(r"\{npc:(\d+):([^}]*)\}", label.group(1))
                if tag:
                    npc = npc or tag
                    name = tag.group(2)
                else:
                    name = label.group(1)
            if not (npc and name):
                continue
            npc_id = int(npc.group(1))
            coords = [coord] + re.findall(r"\d{8}", (re.search(r"--\s*\[([\d,\s]+)\]", body) or [None, ""])[1])
            pts = []
            for cc in coords:
                p = (int(cc[:4]) / 10000, int(cc[4:]) / 10000)
                if p not in pts:
                    pts.append(p)
            if npc_id in out:
                out[npc_id][3].extend(p for p in pts if p not in out[npc_id][3])
            else:
                out[npc_id] = [npc_id, name, zone, pts]
    return list(out.values())


if __name__ == "__main__":
    sd_path = sys.argv[2] if len(sys.argv) > 2 else None
    main(sys.argv[1])
